import { chromium } from '@playwright/test'
const b = await chromium.launch({ executablePath: process.env.CHROME || undefined })
const p = await b.newPage({ viewport: { width: 1440, height: 900 } })
const errs = []; p.on('pageerror', (e) => errs.push(String(e))); p.on('console', (m) => { if (m.type() === 'error') errs.push(m.text()) })
await p.goto('http://localhost:4173/', { waitUntil: 'networkidle' })
await p.waitForTimeout(3000)
await p.screenshot({ path: 'tests/out/wb-idle.png' })
await p.mouse.move(300, 560); await p.waitForTimeout(250); await p.mouse.move(420, 600); await p.waitForTimeout(1200)
await p.screenshot({ path: 'tests/out/wb-reach.png' })
await p.evaluate(() => document.documentElement.dataset.theme = 'dark'); await p.waitForTimeout(500)
await p.screenshot({ path: 'tests/out/wb-dark.png' })
const m = await b.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })
await m.goto('http://localhost:4173/', { waitUntil: 'networkidle' }); await m.waitForTimeout(2500)
await m.screenshot({ path: 'tests/out/wb-phone.png', fullPage: false })
console.log(errs)
await b.close()
