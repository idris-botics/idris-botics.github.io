import { chromium } from '@playwright/test'
const u = 'https://idris-botics.github.io/'
const b = await chromium.launch()
const p = await b.newPage({ viewport: { width: 1440, height: 900 } })
const errs = []; p.on('pageerror', (e) => errs.push(e.message))
await p.goto(u, { waitUntil: 'networkidle' })
const order = await p.$$eval('main h2', (h) => h.map((x) => x.textContent))
console.log('h2 order:', order.join(' | '))
console.log('awards cards:', await p.locator('#awards .award').count())
console.log('path has InnovateX:', await p.locator('#path').getByText('InnovateX').count())
await p.goto(u + '#work/robodog', { waitUntil: 'networkidle' }); await p.reload({ waitUntil: 'networkidle' })
console.log('interest prompt:', await p.locator('.interest').innerText())
await p.goto(u + 'work/robodog/', { waitUntil: 'networkidle' }); await p.waitForTimeout(800)
console.log('share page redirects to:', p.url())
await p.locator('#contact').first().scrollIntoViewIfNeeded().catch(() => {})
const m = await b.newPage({ viewport: { width: 360, height: 800 } }); await m.goto(u, { waitUntil: 'networkidle' })
console.log('360 overflow:', await m.evaluate(() => document.documentElement.scrollWidth > innerWidth))
console.log('errors:', errs.length)
await b.close()
